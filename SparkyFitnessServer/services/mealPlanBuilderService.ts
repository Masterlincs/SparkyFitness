// Weekly meal plans built from saved meals: generated by rule from the
// person's own meals, or from recipes their AI provider writes. Either way the
// result is an ordinary, inactive meal plan template they can edit and turn on.

export type PlanSlot = 'breakfast' | 'lunch' | 'dinner' | 'snacks';

export interface PlannableMeal {
  id: string;
  name: string;
  /** Calories in one serving. */
  calories: number;
  /** The slot the meal is meant for, when known. */
  slot?: PlanSlot | null;
}

export interface PlanAssignment {
  day_of_week: number;
  meal_type: PlanSlot;
  meal_id: string;
  quantity: number;
}

// Share of the day's calories each slot aims at.
export const PLAN_SLOTS: ReadonlyArray<{ slot: PlanSlot; share: number }> = [
  { slot: 'breakfast', share: 0.25 },
  { slot: 'lunch', share: 0.3 },
  { slot: 'dinner', share: 0.35 },
  { slot: 'snacks', share: 0.1 },
];

const SLOT_WORDS: Record<PlanSlot, RegExp> = {
  breakfast:
    /\b(porridge|oat|toast|egg|cereal|muesli|granola|pancake|yog(h)?urt|smoothie|bacon|breakfast|crumpet|bagel|kipper|kedgeree)/i,
  snacks:
    /\b(cake|biscuit|flapjack|scone|muffin|bar|crisp|cookie|fruit|nuts|shortbread|tea ?loaf|bun|bara brith|welsh cake)/i,
  lunch: /\b(soup|sandwich|salad|wrap|butty|rarebit|ploughman|jacket)/i,
  dinner:
    /\b(pie|roast|stew|hotpot|curry|casserole|chilli|lasagne|pasta|fish|sausage|mash|steak|chicken|toad)/i,
};

/** Guesses a meal's slot from its name, or null when nothing fits. */
export function guessSlot(name: string): PlanSlot | null {
  for (const slot of ['breakfast', 'snacks', 'lunch', 'dinner'] as const) {
    if (SLOT_WORDS[slot].test(name)) return slot;
  }
  return null;
}

// Servings move in halves between half a serving and two.
const servingsFor = (target: number, calories: number) =>
  Math.min(2, Math.max(0.5, Math.round((target / calories) * 2) / 2));

/**
 * Fills seven days of breakfast, lunch, dinner and snacks from the meals given,
 * aiming each slot at its share of the daily target. Meals meant for a slot are
 * preferred; lunch and dinner fall back to any main meal; a slot with nothing
 * suitable is left empty. The same meal is not repeated in a slot within two
 * days when there is a choice.
 */
export function planWeek(
  meals: PlannableMeal[],
  dailyTarget: number
): PlanAssignment[] {
  const usable = meals.filter((meal) => meal.calories > 0);
  const slotOf = (meal: PlannableMeal) => meal.slot ?? guessSlot(meal.name);
  const pools: Record<PlanSlot, PlannableMeal[]> = {
    breakfast: usable.filter((meal) => slotOf(meal) === 'breakfast'),
    snacks: usable.filter((meal) => slotOf(meal) === 'snacks'),
    lunch: usable.filter((meal) => slotOf(meal) === 'lunch'),
    dinner: usable.filter((meal) => slotOf(meal) === 'dinner'),
  };
  const mains = usable.filter((meal) => {
    const slot = slotOf(meal);
    return slot === null || slot === 'lunch' || slot === 'dinner';
  });
  if (pools.lunch.length === 0) pools.lunch = mains;
  if (pools.dinner.length === 0) pools.dinner = mains;

  const assignments: PlanAssignment[] = [];
  const recent: Record<PlanSlot, string[]> = {
    breakfast: [],
    lunch: [],
    dinner: [],
    snacks: [],
  };
  for (let day = 0; day < 7; day++) {
    const usedToday = new Set<string>();
    for (const { slot, share } of PLAN_SLOTS) {
      const pool = pools[slot];
      if (pool.length === 0) continue;
      const target = dailyTarget * share;
      let best: { meal: PlannableMeal; quantity: number; cost: number } | null =
        null;
      for (const meal of pool) {
        const quantity = servingsFor(target, meal.calories);
        let cost = Math.abs(meal.calories * quantity - target) / target;
        // Yesterday's meal in this slot weighs more than the day before's.
        const lastUsed = recent[slot].indexOf(meal.id);
        if (lastUsed === 0) cost += 1.5;
        else if (lastUsed === 1) cost += 0.5;
        if (usedToday.has(meal.id)) cost += 2;
        if (!best || cost < best.cost) best = { meal, quantity, cost };
      }
      if (!best) continue;
      usedToday.add(best.meal.id);
      recent[slot] = [best.meal.id, ...recent[slot]].slice(0, 2);
      assignments.push({
        day_of_week: day,
        meal_type: slot,
        meal_id: best.meal.id,
        quantity: best.quantity,
      });
    }
  }
  return assignments;
}

/** The person's saved meals with calories per serving. */
async function getPlannableMeals(userId: string): Promise<PlannableMeal[]> {
  const client = await getClient(userId);
  try {
    const result = await client.query(
      `SELECT m.id, m.name, m.total_servings,
              SUM(COALESCE(mf.calories, 0) * mf.quantity
                  / NULLIF(mf.serving_size, 0)) AS total_calories
       FROM meals m
       JOIN meal_foods mf ON mf.meal_id = m.id AND mf.item_type = 'food'
       WHERE m.user_id = $1
       GROUP BY m.id`,
      [userId]
    );
    return result.rows.map(
      (row: {
        id: string;
        name: string;
        total_servings: string | number | null;
        total_calories: string | number | null;
      }) => ({
        id: row.id,
        name: row.name,
        calories:
          (Number(row.total_calories) || 0) / (Number(row.total_servings) || 1),
      })
    );
  } finally {
    client.release();
  }
}

async function resolveDailyTarget(
  userId: string,
  override: number | undefined
): Promise<number> {
  if (override && override > 0) return override;
  const today = todayInZone(await loadUserTimezone(userId));
  const goals = (await getUserGoals(userId, today)) as { calories?: unknown };
  return Number(goals?.calories) || 2000;
}

async function saveTemplate(
  userId: string,
  planName: string,
  description: string,
  startDate: string,
  assignments: PlanAssignment[]
) {
  return createMealPlanTemplate(userId, {
    plan_name: planName,
    description,
    start_date: startDate,
    end_date: addDays(startDate, 6),
    is_active: false,
    assignments: assignments.map((assignment) => ({
      ...assignment,
      item_type: 'meal',
      unit: 'serving',
    })),
  });
}

export class NotEnoughMealsError extends Error {}
export class NoAiServiceError extends Error {}
export class AiPlanError extends Error {}

/** Generates an inactive weekly plan from the person's saved meals. */
export async function generateMealPlan(
  userId: string,
  options: { startDate: string; calorieTarget?: number; name?: string }
) {
  const meals = await getPlannableMeals(userId);
  const target = await resolveDailyTarget(userId, options.calorieTarget);
  const assignments = planWeek(meals, target);
  if (assignments.length === 0) {
    throw new NotEnoughMealsError(
      'Save some meals first, for example by importing starter recipes.'
    );
  }
  const template = await saveTemplate(
    userId,
    options.name || `Generated plan from ${options.startDate}`,
    `Generated from your saved meals for about ${Math.round(target)} kcal a day. Edit it, then turn it on.`,
    options.startDate,
    assignments
  );
  return { template, daily_target: Math.round(target), assignments };
}

const AI_RECIPE_SCHEMA: JsonSchemaNode = {
  type: 'object',
  properties: {
    recipes: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          name: { type: 'string' },
          slot: {
            type: 'string',
            enum: ['breakfast', 'lunch', 'dinner', 'snacks'],
          },
          servings: { type: 'number' },
          ingredients: { type: 'array', items: { type: 'string' } },
          method: { type: 'array', items: { type: 'string' } },
        },
        required: ['name', 'slot', 'servings', 'ingredients', 'method'],
        additionalProperties: false,
      },
    },
  },
  required: ['recipes'],
  additionalProperties: false,
};

interface AiRecipe {
  name: string;
  slot: PlanSlot;
  servings: number;
  ingredients: string[];
  method: string[];
}

function readAiRecipes(json: unknown): AiRecipe[] {
  const recipes = (json as { recipes?: unknown })?.recipes;
  if (!Array.isArray(recipes)) return [];
  return recipes.flatMap((raw): AiRecipe[] => {
    const recipe = raw as Partial<AiRecipe>;
    if (
      typeof recipe.name !== 'string' ||
      !recipe.name.trim() ||
      !Array.isArray(recipe.ingredients) ||
      !['breakfast', 'lunch', 'dinner', 'snacks'].includes(String(recipe.slot))
    ) {
      return [];
    }
    return [
      {
        name: recipe.name.trim().slice(0, 120),
        slot: recipe.slot as PlanSlot,
        servings: Number(recipe.servings) || 2,
        ingredients: recipe.ingredients.filter(
          (line): line is string => typeof line === 'string'
        ),
        method: Array.isArray(recipe.method)
          ? recipe.method.filter(
              (step): step is string => typeof step === 'string'
            )
          : [],
      },
    ];
  });
}

function aiPrompt(target: number, preferences: string | undefined) {
  return [
    'Write recipes for one week of meals for someone in the UK.',
    `Their daily calorie target is about ${Math.round(target)} kcal: breakfast about 25%, lunch 30%, dinner 35%, snacks 10%.`,
    'Write 3 breakfasts, 3 lunches, 5 dinners and 2 snacks, using ingredients from UK supermarkets.',
    'Give every ingredient on its own line with a metric amount, for example "200 g chicken breast" or "1 tbsp olive oil". Do not combine ingredients on one line.',
    'servings is how many portions the recipe makes. Keep methods short.',
    preferences?.trim()
      ? `Their preferences and restrictions (follow these): ${preferences.trim()}`
      : '',
  ]
    .filter(Boolean)
    .join('\n');
}

/**
 * Asks the person's AI provider for a week of recipes, saves each as a meal
 * with its ingredients matched to UK foods, and plans a week from them.
 */
export async function generateAiMealPlan(
  userId: string,
  actorUserId: string,
  actorIsAdmin: boolean,
  options: {
    startDate: string;
    calorieTarget?: number;
    preferences?: string;
  }
) {
  const setting = await chatRepository.getActiveAiServiceSetting(actorUserId);
  const aiService = setting
    ? await chatRepository.getAiServiceSettingForBackend(
        setting.id,
        actorUserId
      )
    : null;
  if (!aiService) {
    throw new NoAiServiceError('Set up an AI service in Settings first.');
  }
  const target = await resolveDailyTarget(userId, options.calorieTarget);
  const result = await dispatchAiRequest({
    provider: {
      service_type: aiService.service_type,
      api_key: aiService.api_key ?? undefined,
      model_name: aiService.model_name ?? undefined,
      custom_url: aiService.custom_url ?? undefined,
    },
    networkPolicy: await resolveAiNetworkPolicy(aiService, actorIsAdmin),
    prompt: aiPrompt(target, options.preferences),
    jsonSchema: AI_RECIPE_SCHEMA,
    schemaName: 'weekly_recipes',
    timeoutMs: 240_000,
  });
  if (!result.ok) {
    log(
      'warn',
      `AI meal plan failed for ${userId} (${result.category}): ${result.detail}`
    );
    throw new AiPlanError(
      `The AI service could not write recipes: ${result.detail}`
    );
  }
  const recipes = readAiRecipes(result.json).slice(0, 16);
  if (recipes.length === 0) {
    throw new AiPlanError('The AI service returned no usable recipes.');
  }

  const model = aiService.model_name || aiService.service_type;
  const built: Array<BuiltMeal & { slot: PlanSlot }> = [];
  const failed: string[] = [];
  for (const recipe of recipes) {
    try {
      const meal = await buildMealFromRecipe(userId, {
        name: recipe.name,
        servings: recipe.servings,
        ingredients: recipe.ingredients,
        notes: [
          recipe.method.length > 0
            ? `**Method**\n\n${recipe.method.map((step, i) => `${i + 1}. ${step}`).join('\n')}`
            : null,
          `Written by an AI model (${model}). It has not been reviewed by a dietitian; check it suits you.`,
        ]
          .filter(Boolean)
          .join('\n\n'),
      });
      built.push({ ...meal, slot: recipe.slot });
    } catch (error) {
      log('warn', `AI recipe "${recipe.name}" could not be saved:`, error);
      failed.push(recipe.name);
    }
  }
  const assignments = planWeek(
    built.map((meal) => ({
      id: meal.meal_id,
      name: meal.name,
      calories: meal.calories_per_serving,
      slot: meal.slot,
    })),
    target
  );
  if (assignments.length === 0) {
    throw new AiPlanError('None of the AI recipes could be matched to foods.');
  }
  const template = await saveTemplate(
    userId,
    `AI plan from ${options.startDate}`,
    `Recipes written by ${model} for about ${Math.round(target)} kcal a day. Not reviewed by a dietitian. Edit it, then turn it on.`,
    options.startDate,
    assignments
  );
  return {
    template,
    daily_target: Math.round(target),
    meals: built,
    failed,
  };
}
